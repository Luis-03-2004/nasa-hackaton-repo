// Regressão com a base real: histórico completo, calendário, filtros e ícones.
// FIRECAL_URL, PLAYWRIGHT_MODULE e CHROME_BIN permitem testar local ou HTTPS.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({ ...(process.env.CHROME_BIN ? { executablePath: process.env.CHROME_BIN } : {}), headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
 try {
  const page = await browser.newPage({ viewport: { width: 1450, height: 1100 }, acceptDownloads: true });
  page.setDefaultTimeout(60000);
  const errors = [], failed = [], evidence = {};
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400 && r.url().includes('/api/')) failed.push(`${r.status()} ${r.url()}`); });
  const response = (path, condition = () => true) => page.waitForResponse(r => {
   if (!r.url().endsWith(path) || r.request().method() !== 'POST') return false;
   try { return condition(r.request().postDataJSON()); } catch { return false; }
  }, { timeout: 180000 });
  const json = async promise => { const r = await promise; assert.equal(r.status(), 200); return r.json(); };
  const noEmojis = async () => assert.deepEqual((await page.locator('body').innerText()).match(/\p{Extended_Pictographic}/gu) || [], [], 'Ícones da interface devem ser SVG');
  const initial = response('/explore/query');
  const initialForecast = response('/forecast/selection');
  await page.goto(process.env.FIRECAL_URL || 'http://127.0.0.1:18011', { waitUntil: 'domcontentloaded' });
  const full = await json(initial);
  assert.equal(full.filters.start_date, '2000-01-01');
  assert.equal(full.filters.end_date, '2025-12-31');
  assert.equal(full.timeseries.length, 312);
  assert.equal(full.totals.value, 295748529);
  assert.ok(full.timeseries[0].period.startsWith('2000-01'));
  assert.ok(full.timeseries.at(-1).period.startsWith('2025-12'));
  evidence.history = { months: full.timeseries.length, total: full.totals.value };
  await page.getByRole('heading', { name: 'Observed time series', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Start date', { exact: true }).inputValue(), '2000-01-01');
  const calendar = page.getByRole('table', { name: 'Selection calendar', exact: true });
  await calendar.waitFor();
  assert.equal(await calendar.getByTitle(/^Drill down into months of \d{4}$/).count(), 26);
  const forecast = await json(initialForecast);
  assert.ok(forecast.available); assert.equal(forecast.forecasts.length, 4);
  await page.getByRole('button', { name: 'Project Forecast on Map', exact: true }).click();
  await page.getByText('F₂ FORECAST MODE ON MAP:', { exact: false }).waitFor();
  await noEmojis();
  await page.getByRole('button', { name: 'Return to historical observations', exact: true }).click();
  await page.getByRole('button', { name: 'BAT AI Assistant', exact: true }).click();
  await page.getByLabel('BAT Assistant', { exact: true }).waitFor();
  await noEmojis();
  await page.getByRole('button', { name: 'Close assistant', exact: true }).click();
  await noEmojis();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click();
  const csv = fs.readFileSync(await (await download).path(), 'utf8');
  assert.equal(csv.split('\n').filter(line => line.startsWith('"observation"')).length, 312);
  assert.ok(csv.includes('2000-01')); assert.ok(csv.includes('2025-12'));
  const year2025 = response('/explore/query', q => q.start_date === '2025-01-01');
  await page.getByRole('button', { name: '1Y (2025)', exact: true }).click();
  assert.equal((await json(year2025)).timeseries.length, 12);
  await page.getByLabel('Calendar year', { exact: true }).waitFor();
  const year2024 = response('/explore/query', q => q.start_date === '2024-01-01' && q.end_date === '2024-12-31');
  await page.getByLabel('Calendar year', { exact: true }).selectOption('2024');
  const historical = await json(year2024);
  assert.equal(historical.timeseries.length, 12); assert.ok(historical.totals.value > 0);
  assert.equal(await page.getByLabel('Start date', { exact: true }).inputValue(), '2024-01-01');
  await page.getByRole('button', { name: /Jan 2024.*Mean:/ }).waitFor();
  const allAgain = response('/explore/query', q => q.start_date === '2000-01-01');
  await page.getByRole('button', { name: /All \(2000.?2025\)/ }).click();
  assert.equal((await json(allAgain)).timeseries.length, 312);
  await calendar.getByTitle('Drill down into months of 2000', { exact: true }).click();
  const missing = response('/explore/calendar-month', q => q.year === 2000 && q.month === 1);
  await page.getByRole('button', { name: 'View days ▸', exact: true }).nth(0).click();
  const missingDays = await json(missing); assert.ok(missingDays.days.every(d => d.value === null));
  await page.getByTestId('calendar-source').filter({ hasText: 'No data available' }).waitFor();
  await page.getByTitle('2000-01-01: No data', { exact: false }).waitFor();
  const boundary = page.getByRole('button', { name: 'Prev mo.', exact: true }); assert.ok(await boundary.isDisabled());
  await page.getByRole('button', { name: /^Months \(2000\)$/ }).click();
  const estimated = response('/explore/calendar-month', q => q.year === 2000 && q.month === 11);
  await page.getByRole('button', { name: 'View days ▸', exact: true }).nth(10).click();
  const estimatedDays = await json(estimated); assert.ok(estimatedDays.is_estimated);
  assert.ok(['monthly_distributed', 'weekly_distributed'].includes(estimatedDays.source));
  await page.getByTestId('calendar-source').filter({ hasText: 'Days estimated' }).waitFor();
  evidence.calendar = { missing2000: missingDays.days.length, estimatedSource: estimatedDays.source, year2024: historical.totals.value };
  const portuguese = response('/explore/query', q => q.locale === 'pt-BR');
  await page.getByLabel('Language', { exact: true }).selectOption('pt-BR');
  await json(portuguese);
  await page.getByRole('heading', { name: 'Série temporal observada', exact: true }).waitFor();
  assert.equal(await page.locator('html').getAttribute('lang'), 'pt-BR');
  await noEmojis();
  await page.screenshot({ path: '/tmp/firecal-historico-desktop.png', fullPage: true });
  const english = response('/explore/query', q => q.locale === 'en');
  await page.getByLabel('Idioma', { exact: true }).selectOption('en'); await json(english);
  const explicit = response('/explore/query', q => q.start_date === '2025-10-01');
  await page.getByRole('button', { name: '3M (Q4 2025)', exact: true }).click();
  assert.equal((await json(explicit)).timeseries.length, 3);
  await page.getByRole('button', { name: 'Share filters', exact: true }).click();
  assert.ok(new URL(page.url()).hash.includes('explore='));
  const restored = response('/explore/query', q => q.start_date === '2025-10-01');
  await page.reload({ waitUntil: 'domcontentloaded' }); assert.equal((await json(restored)).timeseries.length, 3);
  assert.equal(await page.getByLabel('Start date', { exact: true }).inputValue(), '2025-10-01');
  await noEmojis();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
  await page.screenshot({ path: '/tmp/firecal-historico-mobile.png', fullPage: true });
  assert.deepEqual(errors, []); assert.deepEqual(failed, []);
  fs.writeFileSync('/tmp/firecal-historico-result.json', JSON.stringify({ ...evidence, errors, failed }, null, 2));
  console.log('PASS: 312 meses, 26 anos, CSV completo, navegação 2025→2024, dias ausentes/estimados, SVG, PT-BR/EN, filtros compartilhados e mobile');
 } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });

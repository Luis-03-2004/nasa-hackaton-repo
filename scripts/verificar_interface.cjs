// E2E: exige API e Vite locais. Playwright/Chrome podem vir do ambiente.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({ ...(process.env.CHROME_BIN ? { executablePath: process.env.CHROME_BIN } : {}), headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
 try {
  const page = await browser.newPage({ viewport: { width: 1450, height: 1100 }, acceptDownloads: true });
  await page.addInitScript(() => { if (!localStorage.getItem('bat.locale')) localStorage.setItem('bat.locale', 'pt-BR'); });
  page.setDefaultTimeout(60000);
  const errors=[],failed=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400&&!r.url().includes('favicon'))failed.push(`${r.status()} ${r.url()}`)});
  page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE',m.text().slice(0,400))});
  const result=(path,condition=()=>true)=>page.waitForResponse(r=>{
   if(!r.url().endsWith(path)||r.request().method()!=='POST')return false;
   try{return condition(r.request().postDataJSON())}catch{return false}
  },{timeout:180000});
  const init=result('/explore/query');
  await page.goto(process.env.FIRECAL_URL||'http://127.0.0.1:5173',{waitUntil:'domcontentloaded'});
  assert.equal((await init).status(),200);
  await page.getByRole('heading',{name:'Série temporal observada'}).waitFor();
  assert.equal(await page.locator('html').getAttribute('lang'),'pt-BR');
  const info=page.getByRole('button',{name:'Informações: unidades e sensores',exact:true});
  assert.equal(await info.getAttribute('aria-expanded'),'false');
  await info.click();assert.equal(await info.getAttribute('aria-expanded'),'true');await info.click();
  assert.equal(await info.getAttribute('aria-expanded'),'false');
  const english=result('/explore/query',q=>q.locale==='en');
  await page.getByLabel('Idioma',{exact:true}).selectOption('en');assert.equal((await english).status(),200);
  await page.getByRole('heading',{name:'Observed time series'}).waitFor();
  assert.equal(await page.locator('html').getAttribute('lang'),'en');
  assert.equal(await page.getByLabel('Start date',{exact:true}).inputValue(),'2000-01-01');
  await page.getByLabel('Search country',{exact:true}).fill('Canada');
  const country=result('/explore/query',q=>q.country==='Canada');
  await page.getByLabel('Country / territory',{exact:true}).selectOption('Canada');assert.equal((await country).status(),200);
  const current=result('/explore/query',q=>q.country==='Canada'&&q.start_date==='2025-01-01');
  await page.getByLabel('Start date',{exact:true}).fill('2025-01-01');
  const initial=await(await current).json();assert.ok(initial.totals.value>0);assert.equal(initial.timeseries.length,12);
  await page.getByRole('button',{name:'2D heatmap',exact:true}).click();await page.getByLabel('Compare years',{exact:true}).check();
  const older=result('/explore/map',q=>q.start_date==='2000-01-01'&&q.country==='Canada');
  await page.getByLabel('Year B',{exact:true}).selectOption('2000');const oldData=await(await older).json();assert.ok(oldData.coverage.partial);
  const canvas=page.getByRole('img',{name:/Interactive 2D map/}).first();await canvas.waitFor();
  await canvas.hover(); await page.mouse.wheel(0,-300);
  await page.getByRole('button',{name:'Zoom in map',exact:true}).first().click();
  const world=result('/explore/query',q=>q.country===null);
  await page.getByRole('button',{name:'World',exact:true}).first().click();
  assert.equal((await world).status(),200);
  const countryAgain=result('/explore/query',q=>q.country==='Canada');
  const mapAgain=result('/explore/map',q=>q.country==='Canada'&&q.start_date==='2025-01-01');
  await page.getByLabel('Country / territory',{exact:true}).selectOption('Canada');
  await countryAgain;await mapAgain;
  const box=await canvas.boundingBox();
  await page.keyboard.down('Shift');await page.mouse.move(box.x+5,box.y+5);await page.mouse.down();
  await page.mouse.move(box.x+box.width-5,box.y+box.height-5,{steps:12});
  const selectedResponse=result('/explore/query',q=>q.point_ids.length>100);
  await page.mouse.up();await page.keyboard.up('Shift');
  const response=await selectedResponse;assert.equal(response.status(),200);const selected=await response.json();
  assert.ok(selected.selected_count>100);assert.equal(selected.processed_count,selected.selected_count);
  // O retângulo inclui as células visíveis; a câmera pode recortar células do país.
  assert.ok(selected.totals.value>0&&selected.totals.value<=initial.totals.value);
  console.log('MULTI',selected.selected_count,selected.processed_count,selected.totals.value);
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export CSV',exact:true}).click();
  const csv=fs.readFileSync(await(await downloadPromise).path(),'utf8');
  assert.ok(csv.includes('metadata'));assert.ok(csv.includes('point_ids'));assert.ok(csv.includes('2025-12-01'));
  await page.getByRole('button',{name:'Share filters',exact:true}).click();
  assert.ok(new URL(page.url()).hash.includes('explore='));
  const restored=result('/explore/query',q=>q.point_ids.length===selected.selected_count);
  await page.reload({waitUntil:'domcontentloaded'});
  assert.equal((await restored).status(),200);
  const pt=result('/explore/query',q=>q.locale==='pt-BR');await page.getByLabel('Language',{exact:true}).selectOption('pt-BR');await pt;
  assert.equal(await page.getByLabel('País / território',{exact:true}).inputValue(),'Canada');
  await page.getByLabel('Comparar anos',{exact:true}).uncheck();await page.getByRole('button',{name:'Calor 3D',exact:true}).click();
  await page.getByRole('button',{name:'Aproximar globo',exact:true}).waitFor();
  await page.screenshot({path:'/tmp/firecal-v2-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Observações 2D',exact:true}).click();await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth);
  await page.screenshot({path:'/tmp/firecal-v2-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(failed,[]);
  console.log('PASS: PT-BR/EN, information, countries, dates, zoom, A/B, Shift, CSV, 3D/mobile; no JS/HTTP errors');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});

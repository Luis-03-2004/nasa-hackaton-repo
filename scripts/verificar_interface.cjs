// Teste E2E com serviços e dados reais já disponíveis. Playwright é opcional.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ ...(process.env.CHROME_BIN ? { executablePath: process.env.CHROME_BIN } : {}), headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
  try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1100 }, acceptDownloads: true });
  const errors = [];
  const failed = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) failed.push(`${r.status()} ${r.url()}`) });
  page.on('console', m => { if (m.type() === 'error') console.log('BROWSER ERROR', m.text().slice(0,500)) });
  await page.goto(process.env.FIRECAL_URL || 'http://127.0.0.1:5173', { waitUntil: 'networkidle' });
  await page.getByText('16.525 pontos', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Baixar CSV do histórico' }).waitFor();
  await page.getByText('Carregando previsão do catálogo…').waitFor({ state: 'hidden' });
  console.log('INITIAL', (await page.locator('main').innerText()).slice(0,700));
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Baixar CSV do histórico' }).click();
  const download = await downloadPromise;
  assert.match(download.suggestedFilename(), /global_mensal_2000_2025\.csv/);
  const path = await download.path();
  const csv = require('node:fs').readFileSync(path, 'utf8');
  assert.equal(csv.trim().split('\n').length, 313);
  assert.match(csv, /2000-01-01/); assert.match(csv, /2025-12-01/);
  console.log('CSV', download.suggestedFilename(), '312 rows');
  await page.getByRole('button', { name: 'Pantanal', exact: true }).click();
  await page.getByText('Carregando previsão do catálogo…').waitFor({ state: 'hidden' });
  assert.equal(await page.getByLabel('Escopo do histórico', { exact: true }).inputValue(), 'brazil');
  await page.getByLabel('Latitude', { exact: true }).fill('37.5');
  await page.getByLabel('Longitude', { exact: true }).fill('-120.5');
  await page.getByRole('button', { name: 'Consultar ponto F₂', exact: true }).click();
  await page.getByText('Carregando previsão do catálogo…').waitFor({ state: 'hidden' });
  assert.match(await page.locator('aside').innerText(), /United States/);
  await page.getByRole('button', { name: 'Mapa 2D', exact: true }).click();
  const mapCanvas = page.getByRole('img', { name: /pontos do catálogo F2/ });
  const canvasBox = await mapCanvas.boundingBox();
  const locationResponse = page.waitForResponse(r => r.url().includes('/api/forecast/location?') && r.status() === 200);
  await mapCanvas.click({ position: { x: (180 - 51.5) / 360 * canvasBox.width, y: (90 + 11.5) / 180 * canvasBox.height } });
  await locationResponse;
  await page.getByText('Carregando previsão do catálogo…').waitFor({ state: 'hidden' });
  assert.match(await page.locator('aside').innerText(), /Brazil/);
  assert.equal(Number(await page.getByLabel('Latitude', { exact: true }).inputValue()), -11.5);
  await page.getByRole('button', { name: 'Sensores (ano selecionado)', exact: true }).click();
  await page.getByText('Consultando sensores em 2025…').waitFor({ state: 'hidden' });
  assert.match(await page.locator('main').innerText(), /Não harmonizadas/);
  await page.getByRole('button', { name: 'Histórico harmonizado', exact: true }).click();
  await page.getByRole('button', { name: 'Calendário', exact: true }).click();
  console.log('CALENDAR BUTTONS', await page.locator('#calendar button').count());
  await page.getByRole('button', { name: '2025 · Jul:', exact: false }).click();
  assert.equal(await page.getByLabel('Mês', { exact: true }).inputValue(), '2025-07');
  await page.getByLabel('Área oeste sul leste norte', { exact: true }).fill('-47.831, -23.531, -47.829, -23.529');
  await page.getByRole('button', { name: 'Consultar 2025-07', exact: true }).click();
  await page.getByText('Consultando…', { exact: true }).waitFor({ state: 'hidden', timeout: 30000 });
  console.log('AREA', await page.locator('table').filter({ hasText: 'Semana (UTC)' }).innerText());
  assert.match(await page.locator('table').filter({ hasText: 'Semana (UTC)' }).innerText(), /modis/);
  await page.screenshot({ path: '/tmp/firecal-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
  await page.screenshot({ path: '/tmp/firecal-mobile.png', fullPage: true });
  const dimensions = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: window.innerWidth }));
  assert.ok(dimensions.scroll <= dimensions.viewport, JSON.stringify(dimensions));
  assert.deepEqual(errors, []); assert.deepEqual(failed, []);
  console.log('PASS: API/proxy, full catalog, point selection, region, CSV, sensor series, real area, mobile layout; no JS or HTTP errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
